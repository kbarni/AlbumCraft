//! The built-in vocabulary of tag proposals: tags for personal photos, proposed by the search
//! networks with no example from the user (`tag_proposals`). Each has a translated name
//! (`tag-<id>` in the `.ftl` files; the English here is the fallback) and the English
//! sentence its text vector is made from. A word added here needs its `tag-<id>` in every
//! language's `.ftl` file (`every_word_has_its_english_name` checks the English one).

/// One word: the message key of its name, the English name, the sentence for the networks.
pub struct Word {
    pub key: &'static str,
    pub english: &'static str,
    pub prompt: &'static str,
}

impl Word {
    /// The name in the interface's language.
    pub fn name(&self) -> String {
        crate::msg::Msg::new(self.key, self.english).to_string()
    }
}

