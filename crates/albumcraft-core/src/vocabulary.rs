#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_word_has_its_english_name() {
        let en = include_str!("../../../i18n/en/albumcraft.ftl");
        let mut keys = std::collections::HashSet::new();
        for w in WORDS {
            assert!(keys.insert(w.key), "{} twice", w.key);
            assert!(en.lines().any(|l| l == format!("{} = {}", w.key, w.english)), "{} = {} is not in en.ftl", w.key, w.english);
            assert!(w.prompt.split_whitespace().count() >= 2, "{}", w.key);
        }
        assert!(WORDS.len() >= 200);
    }
}
